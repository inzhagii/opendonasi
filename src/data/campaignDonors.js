// Helper untuk menggabungkan donasi context lokal (sesi saat ini) dengan data dummy
export function getMergedDonors(campaignSlug, contextDonations = []) {
  // Filter donasi context pengguna untuk kampanye ini
  const userDonations = (contextDonations || [])
    .filter((d) => d && (d.campaignSlug === campaignSlug || !d.campaignSlug))
    .map((d) => ({
      id: d.transactionId || `user-don-${Math.random()}`,
      donorName: d.isAnonymous ? 'Hamba Allah' : d.donorName || 'Donatur Demo',
      isAnonymous: Boolean(d.isAnonymous),
      amount: Number(d.amount) || 10000,
      timeAgo: 'Baru saja',
      timestamp: Date.now(),
      hasBadge: true,
      doa: d.doa || d.message || null,
      aminCount: 0,
    }));

  // Gabungkan user donasi di urutan teratas
  const all = [...userDonations, ...DEFAULT_MOCK_DONORS];
  const seen = new Set();
  return all.filter((item) => {
    if (seen.has(item.id)) return false;
    seen.add(item.id);
    return true;
  });
}
